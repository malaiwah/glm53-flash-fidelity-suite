#!/usr/bin/env python3
"""Render README.md, tables/*.md and index.json from data/*.jsonl.

The tables in README.md are a PURE FUNCTION of the data files. There is no path by
which a table can contain a number that is not in a row, and `--check` fails if the
committed README differs from what the data renders. A PR that edits a table without
editing a row fails; a PR that edits a row without re-rendering fails.

Grouping is by comparability.key -- never by anything a human chose. Each table's
caption spells the key out in English and states what the group is NOT comparable to.

  python3 tools/registry_render.py [--root DIR] [--check]

Offline, stdlib only.
"""

import argparse
import datetime
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import registry_lib as L  # noqa: E402

BEGIN = "<!-- BEGIN GENERATED: tables -->"
