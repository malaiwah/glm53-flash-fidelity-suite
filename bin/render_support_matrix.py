#!/usr/bin/env python3
"""Render the support matrix (lane x surface x profiles x runner) from bin/engines.json.

    python3 bin/render_support_matrix.py            # print the block
    python3 bin/render_support_matrix.py --write    # inject into README.md between markers
    python3 bin/render_support_matrix.py --check    # fail if README drifted from the data

WHY THIS EXISTS.  The single most persistent documentation defect in this repo
has been hand-written support claims: README, bin/README.md and
registry/CONTRIBUTING.md each carried their own prose copy of "which lane can
read which surface", and every one of them was wrong within days of a reader
landing (GGUF landed on the streaming lane in M5 while three documents still
said it was unreachable).  The registry solved the same problem for its tables
with tools/registry_render.py --check; this is the identical pattern for the
support matrix: `bin/engines.json` is the single source of truth, README.md
carries a generated block between markers, and the selftest fails when the
rendered block and the data disagree.  Every other document LINKS to the README
block instead of restating it.

Runner reachability is PROBED from each runner's real argparse declaration
(`--lane` choices), never hand-written -- the same guess-nothing rule the
engine pinning uses.  Stock python3, stdlib only.
"""

from __future__ import annotations

import argparse
import importlib
import json
import sys
from pathlib import Path
from typing import Dict, List

SUITE_ROOT = Path(__file__).resolve().parent.parent
BIN = SUITE_ROOT / "bin"
README = SUITE_ROOT / "README.md"
ENGINES = BIN / "engines.json"

BEGIN = "<!-- BEGIN GENERATED: support-matrix -->"
END = "<!-- END GENERATED: support-matrix -->"
GEN_NOTE = ("<!-- GENERATED by bin/render_support_matrix.py FROM bin/engines.json "
            "and the runners' own argparse declarations -- DO NOT EDIT BY HAND.\n"
            "     Re-render: python3 bin/render_support_matrix.py --write\n"
            "     Verified by bin/selftest_support_matrix.py (render drift fails). -->")


def _lane_choices(module_name: str) -> List[str]:
    """Probe a runner's --lane choices from its real argparse parser.

    Probing the CLI instead of restating it is the point: when a runner gains
    or loses a lane, this render changes by itself and --check catches a stale
    README.  A runner that cannot be imported is a render error, not a silent
    omission.
    """
    sys.path.insert(0, str(BIN))
    try:
        mod = importlib.import_module(module_name)
    finally:
        sys.path.remove(str(BIN))
    parser = mod.build_parser()
    for action in parser._actions:                       # noqa: SLF001
        if action.dest == "lane":
            return [c for c in (action.choices or []) if c != "auto"]
    raise RuntimeError("%s.build_parser() declares no --lane argument" % module_name)


def runner_lanes() -> Dict[str, List[str]]:
    """Which lanes each user-facing runner can actually be asked for."""
    return {
        "bin/measure-cloud": _lane_choices("measure_cloud"),
        "bin/measure-local": _lane_choices("measure_local"),
        "bin/measure": _lane_choices("measure_one"),
    }


def _profiles_cell(lane_spec: dict) -> str:
    """The rates a lane has a profile for, per surface where the data says so."""
    by_surface = lane_spec.get("profile_map_by_surface") or {}
    if by_surface:
        parts = []
        for surface in sorted(by_surface):
            rates = by_surface[surface]
            keys = sorted(rates)
            if keys == ["*"]:
                parts.append("%s: any rate" % surface)
            elif keys == ["native"]:
                parts.append("%s: unquantized" % surface)
            else:
                parts.append("%s: %s bpw" % (surface, ", ".join(keys)))
        return "; ".join(parts)
    pm = lane_spec.get("profile_map") or {}
    if not pm:
        fixed = (lane_spec.get("fixed_flags") or {}).get("--profile")
        return ("fixed: %s" % fixed) if fixed \
            else "no bpw→profile map (profile named by the campaign driver)"
    keys = sorted(pm)
    named = ["%s→%s" % (k, pm[k]) for k in keys]
    return ", ".join(named)


def render() -> str:
    data = json.loads(ENGINES.read_text(encoding="utf-8"))
    lanes = data["lanes"]
    reach = runner_lanes()

    surfaces: List[str] = []
    for spec in lanes.values():
        for s in spec.get("surfaces") or []:
            if s not in surfaces:
                surfaces.append(s)

    lines: List[str] = []
    lines.append(GEN_NOTE)
    lines.append("")
    lines.append("#### Lane × surface (from `bin/engines.json`)")
    lines.append("")
    lane_names = list(lanes)
    header = "| surface | " + " | ".join("`%s`" % n for n in lane_names) + " |"
    lines.append(header)
    lines.append("|---|" + "---|" * len(lane_names))
    for s in surfaces:
        row = ["`%s`" % s]
        for n in lane_names:
            row.append("✓" if s in (lanes[n].get("surfaces") or []) else "—")
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")

    lines.append("#### What each lane is, and how you reach it")
    lines.append("")
    lines.append("| lane | reachable via | receipt class | rates with a profile |")
    lines.append("|---|---|---|---|")
    for n in lane_names:
        spec = lanes[n]
        runners = sorted(r for r, ls in reach.items() if n in ls)
        via = ", ".join("`%s --lane %s`" % (r, n) for r in runners) if runners \
            else "no runner — campaign lane, driven directly (`engines/tools/`)"
        # Only render what the data declares; inventing a label here would be
        # exactly the hand-written claim this generator exists to end.
        rclass = spec.get("receipt_class") or "(not declared)"
        lines.append("| `%s` | %s | %s | %s |"
                     % (n, via, rclass, _profiles_cell(spec)))
    lines.append("")

    # Measured timing per surface, where the data carries one.
    timed = []
    for n in lane_names:
        by_surface = ((lanes[n].get("timing") or {})
                      .get("minutes_per_window_by_surface") or {})
        for s in sorted(by_surface):
            timed.append((n, s, by_surface[s]))
    if timed:
        lines.append("#### Measured minutes per window, per surface")
        lines.append("")
        lines.append("| lane | surface | min/window |")
        lines.append("|---|---|---:|")
        for n, s, v in timed:
            lines.append("| `%s` | `%s` | %s |" % (n, s, v))
        lines.append("")

    lines.append("Reading the matrix: `bin/measure` never rents, so it plans only the")
    lines.append("local lanes and redirects `--lane streaming` to `bin/measure-cloud`;")
    lines.append("`packed` needs a payload store that is not published, and `native-bf16`")
    lines.append("is an unquantized tree — so a surface whose ✓ appears **only** under")
    lines.append("`streaming` is measurable exclusively by renting. A surface with no ✓")
    lines.append("anywhere (MLX, NVFP4, AWQ, GPTQ …) is refused on every lane at plan")
    lines.append("time, for $0.00, even where a bitwise-tested decoder exists under")
    lines.append("[`engines/tools/`](engines/tools/) — a reader no lane lists is not")
    lines.append("reachable. `gguf` reads a llama.cpp shelf repo: `--path` selects the")
    lines.append("build and its scope covers the whole forward, so its rows are not")
    lines.append("rankable against routed-experts-only rows")
    lines.append("([`docs/GGUF-MEASUREMENT.md`](docs/GGUF-MEASUREMENT.md)).")
    return "\n".join(lines)


def inject(readme_text: str, block: str) -> str:
    if BEGIN not in readme_text or END not in readme_text:
        raise RuntimeError("README.md is missing the %s / %s markers" % (BEGIN, END))
    pre, rest = readme_text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    return pre + BEGIN + "\n" + block + "\n" + END + post


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true",
                    help="inject the block into README.md between the markers")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if README.md's block differs from a fresh render")
    ap.add_argument("--readme", default=str(README),
                    help="README to write/check (default: the suite README)")
    args = ap.parse_args(argv)

    block = render()
    readme = Path(args.readme)

    if args.check:
        current = readme.read_text(encoding="utf-8")
        expected = inject(current, block)
        if current != expected:
            print("RENDER DRIFT: %s support-matrix block is not what "
                  "bin/engines.json renders. Re-run: "
                  "python3 bin/render_support_matrix.py --write" % readme,
                  file=sys.stderr)
            return 1
        print("support matrix: README block matches bin/engines.json")
        return 0

    if args.write:
        current = readme.read_text(encoding="utf-8")
        readme.write_text(inject(current, block), encoding="utf-8")
        print("wrote support-matrix block into %s" % readme)
        return 0

    print(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
