#!/usr/bin/env python3
"""Generate the changelog from the commits, which already are one.

    bin/changelog.py                       # since the last tag, to HEAD
    bin/changelog.py --from v0.2.0 --to v0.3.0
    bin/changelog.py --all                 # every tag range, newest first
    bin/changelog.py --check               # is CHANGELOG.md current?

WHY NOT git-cliff / release-drafter.  Both assume Conventional Commits: a
short subject, a machine-readable type, and a body nobody reads. This
repository's commits are the opposite -- long-form prose that explains what
failed and why, often forty lines of it -- and by a convention that has held
across the whole history, the FIRST LINE is already a good changelog entry:

    container: run the measurement as an IMAGE, not as a rented machine
    bundle: a bundled script's DATA is a dependency too -- found by a root capture dying on it
    clouds: dollars per hour is the wrong metric, and on that metric Lambda was misjudged

So the generator is thirty lines of stdlib rather than a pinned Rust binary
with a template language: it takes the first line, splits the topic off at the
first colon, and groups by topic. Adding a tool would add a dependency, a
config file and a second convention, to produce the same list.

The rule about the LAST line matters as much: `Co-Authored-By` trailers and
empty merges are dropped, because a changelog is what changed, not who typed.

Stock python3.9, no installs, no network.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

SUITE = Path(__file__).resolve().parent.parent
SKIP = re.compile(r"^(merge branch|merge pull request|wip\b|fixup!|squash!)", re.I)
# A topic is the lowercase token this repository puts before the first colon --
# `container:`, `bundle:`, `clouds:`, `naming:`. The pattern is deliberately
# strict about the leading lowercase letter, because a subject can also open
# with a FILE (`AGENTS.md: ...`), an identifier (`REFC-006: ...`) or a flag
# (`--pipeline-root: ...`), and grouping by those produces one section per
# commit -- which is a list with extra headings, not a changelog.
TOPIC = re.compile(r"^[a-z][a-z0-9._/+-]{1,23}$")


def git(*args) -> str:
    proc = subprocess.run(["git", "-C", str(SUITE)] + list(args),
                          capture_output=True, text=True)
    if proc.returncode != 0:
        raise SystemExit("git %s failed: %s" % (" ".join(args), proc.stderr.strip()))
    return proc.stdout.rstrip("\n")


def tags():
    """Tags newest-first by commit date, not by string sort.

    v0.10.0 sorts before v0.9.0 alphabetically, and a changelog that puts them
    in that order is wrong in the one way a reader will notice.
    """
    out = git("tag", "--sort=-creatordate")
    return [t for t in out.splitlines() if t.strip()]


def split_subject(subject: str):
    """(topic, text) for one commit subject, or None if it is not an entry.

    Separated from the git call so it can be driven with known answers -- the
    whole grouping rule is here and nowhere else.
    """
    subject = (subject or "").strip()
    if not subject or SKIP.match(subject):
        return None
    topic, _, rest = subject.partition(":")
    if rest.strip() and TOPIC.match(topic.strip()):
        return topic.strip(), rest.strip()
    return "", subject


def entries(rev_range: str):
    out = git("log", "--no-merges", "--pretty=format:%H%x1f%s", rev_range)
    rows = []
    for line in out.splitlines():
        if "\x1f" not in line:
            continue
        sha, subject = line.split("\x1f", 1)
        split = split_subject(subject)
        if split is None:
            continue
        rows.append((split[0], split[1], sha))
    return rows


def render(rev_range: str, heading: str) -> str:
    rows = entries(rev_range)
    if not rows:
        return ""
    lines = ["## %s" % heading, ""]
    by_topic = {}
    for topic, text, sha in rows:
        by_topic.setdefault(topic, []).append((text, sha))
    # Untopiced entries last: they are the ones that did not follow the
    # convention, and burying them at the top would hide the ones that did.
    for topic in sorted(k for k in by_topic if k) + ([""] if "" in by_topic else []):
        if topic:
            lines.append("### %s" % topic)
            lines.append("")
        for text, sha in by_topic[topic]:
            lines.append("- %s (`%s`)" % (text, sha[:12]))
        lines.append("")
    return "\n".join(lines)


def full_changelog() -> str:
    out = ["# Changelog", "",
           "Generated by `bin/changelog.py` from the commit subjects. Do not "
           "edit by hand: the commits are the source, and this file is a view "
           "of them.", ""]
    marks = tags()
    prev = "HEAD"
    heads = []
    for tag in marks:
        heads.append((("%s..%s" % (tag, prev)), "Unreleased" if prev == "HEAD" else prev))
        prev = tag
    if not marks:
        heads = [("HEAD", "Unreleased")]
    else:
        heads.append((prev, prev))
    for rev_range, heading in heads:
        block = render(rev_range, heading)
        if block:
            out.append(block)
    return "\n".join(out).rstrip("\n") + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--from", dest="frm")
    ap.add_argument("--to", default="HEAD")
    ap.add_argument("--all", action="store_true",
                    help="every tag range, newest first (what CHANGELOG.md is)")
    ap.add_argument("--out", help="write here instead of stdout")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if --out is missing or stale, printing the diff "
                         "summary; what CI runs")
    args = ap.parse_args(argv)

    if args.all or args.check:
        text = full_changelog()
    else:
        frm = args.frm
        if frm is None:
            marks = tags()
            frm = marks[0] if marks else None
        rng = ("%s..%s" % (frm, args.to)) if frm else args.to
        heading = "%s..%s" % (frm or "(root)", args.to)
        text = render(rng, heading) or ("## %s\n\n- nothing\n" % heading)

    if args.check:
        target = Path(args.out or (SUITE / "CHANGELOG.md"))
        if not target.is_file():
            sys.stderr.write("%s does not exist; run bin/changelog.py --all "
                             "--out %s\n" % (target, target))
            return 1
        if target.read_text(encoding="utf-8") != text:
            sys.stderr.write("%s is stale; regenerate with bin/changelog.py "
                             "--all --out %s\n" % (target, target))
            return 1
        print("%s is current" % target)
        return 0

    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print("wrote %s (%d bytes)" % (args.out, len(text)))
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
